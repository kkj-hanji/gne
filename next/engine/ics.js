/** Minimal, dependency-free .ics export for a weekly section timetable. */

import { STUDY_DAYS } from "./datetime.js";

const BYDAY = { Monday: "MO", Tuesday: "TU", Wednesday: "WE", Thursday: "TH", Friday: "FR", Saturday: "SA", Sunday: "SU" };

function pad(value) {
  return String(value).padStart(2, "0");
}

function escapeIcs(value) {
  return String(value == null ? "" : value)
    .replace(/\\/g, "\\\\")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,")
    .replace(/\r?\n/g, "\\n");
}

function dateStamp(dateISO, minutes) {
  const [year, month, day] = dateISO.split("-");
  const hours = Math.floor(minutes / 60);
  const mins = minutes % 60;
  return `${year}${month}${day}T${pad(hours)}${pad(mins)}00`;
}

function utcStamp(date = new Date()) {
  return `${date.getUTCFullYear()}${pad(date.getUTCMonth() + 1)}${pad(date.getUTCDate())}T${pad(date.getUTCHours())}${pad(date.getUTCMinutes())}${pad(date.getUTCSeconds())}Z`;
}

/** First Monday on or after the given ISO date. */
export function firstMonday(dateISO) {
  const [year, month, day] = dateISO.split("-").map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  const offset = (8 - date.getUTCDay()) % 7;
  date.setUTCDate(date.getUTCDate() + offset);
  return date.toISOString().slice(0, 10);
}

/**
 * Build a calendar with one recurring weekly event per class.
 * @param {{schedule:Array, group:string, subgroup?:string, version?:string, startDate?:string, weeks?:number}} options
 */
export function buildIcs({ schedule = [], group, subgroup = "", version = "", startDate, weeks = 16 } = {}) {
  if (!group) throw new Error("Choose a section before exporting a calendar.");
  const classes = (Array.isArray(schedule) ? schedule : []).filter((entry) => {
    if (entry.group !== group) return false;
    if (!subgroup) return true;
    const cohorts = String(entry.cohorts || "").split(/\s*,\s*/).filter(Boolean);
    return !cohorts.length || cohorts.includes(group) || cohorts.includes(subgroup);
  });
  if (!classes.length) throw new Error("No published class to export for this section.");

  const start = firstMonday(startDate || new Date().toISOString().slice(0, 10));
  const stamp = utcStamp();
  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//GNDEC Compass Next//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    `X-WR-CALNAME:${escapeIcs(`GNDEC ${group}${subgroup ? ` ${subgroup}` : ""}`)}`,
    "X-WR-TIMEZONE:Asia/Kolkata",
    "BEGIN:VTIMEZONE",
    "TZID:Asia/Kolkata",
    "BEGIN:STANDARD",
    "DTSTART:19700101T000000",
    "TZOFFSETFROM:+0530",
    "TZOFFSETTO:+0530",
    "TZNAME:IST",
    "END:STANDARD",
    "END:VTIMEZONE"
  ];

  classes
    .filter((entry) => STUDY_DAYS.includes(entry.day))
    .sort((a, b) => STUDY_DAYS.indexOf(a.day) - STUDY_DAYS.indexOf(b.day) || a.start - b.start)
    .forEach((entry, index) => {
      lines.push(
        "BEGIN:VEVENT",
        `UID:compass-${group}-${index}-${entry.start}-${entry.subject.replace(/\s+/g, "-").toLowerCase()}@gndec`,
        `DTSTAMP:${stamp}`,
        `DTSTART;TZID=Asia/Kolkata:${dateStamp(start, entry.start)}`,
        `DTEND;TZID=Asia/Kolkata:${dateStamp(start, entry.end)}`,
        `RRULE:FREQ=WEEKLY;BYDAY=${BYDAY[entry.day]};COUNT=${Math.max(1, Math.min(20, Number(weeks) || 16))}`,
        `SUMMARY:${escapeIcs(entry.subject)}`,
        `LOCATION:${escapeIcs(entry.room)}`,
        `DESCRIPTION:${escapeIcs(`${entry.teacher}${version ? ` · release ${version}` : ""}\nGenerated by GNDEC Compass Next from the official weekly timetable. Holidays and date-specific notices may change the actual class.`)}`,
        "TRANSP:OPAQUE",
        "END:VEVENT"
      );
    });

  lines.push("END:VCALENDAR");
  return lines.join("\r\n");
}

export function downloadIcs(filename, content) {
  const blob = new Blob([content], { type: "text/calendar;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename.endsWith(".ics") ? filename : `${filename}.ics`;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
